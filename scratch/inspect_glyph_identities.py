from fontTools.ttLib import TTFont

font_path = '/home/samuelvictor/Downloads/Shree-Tel-0908 Regular/Shree-Tel-0908 Regular.ttf'
font = TTFont(font_path)
cmap = font.getBestCmap()

# Map of interesting codes
codes = [
    0x61, 0x51, 0x56, 0x52, 0x5A, 0x5E, 0x62, 0x5C, 0x6D, 0x70,
    0x72, 0x75, 0x79, 0x7C, 0x7E, 0x2122, 0xA3, 0xA7, 0xAE, 0xAF,
    0xB2, 0xB8, 0xBA, 0xBF, 0xC4, 0xC5, 0x2C6, 0xCB, 0xD0,
    0xD4, 0xD9, 0xDC, 0x2DC, 0xC3, 0x201E, 0x201A,
    0xE6, 0xE7, 0xE9, 0xEC, 0xED, 0xEE, 0xEF, 0xF0, 0xF1, 0xF2, 0xF6, 0xF8, 0xFA, 0x23, 0xA2
]

for c in codes:
    if c in cmap:
        print(f"0x{c:04X} ({c:5d}) '{chr(c)}': glyph={cmap[c]}")
    else:
        print(f"0x{c:04X} ({c:5d}) NOT IN CMAP")
