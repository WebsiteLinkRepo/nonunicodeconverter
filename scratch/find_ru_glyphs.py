import os
from PIL import Image, ImageDraw, ImageFont
import fontTools.ttLib as ttLib

font_path = "public/SHREE-TEL.ttf"
tt = ttLib.TTFont(font_path)
cmap = tt['cmap'].getBestCmap()

font = ImageFont.truetype(font_path, 40)
label_font = ImageFont.truetype("/usr/share/fonts/TTF/DejaVuSans.ttf", 14)

# Test characters around 0x00A0 - 0x00FF and 0x2000+
codes_to_check = [
    0x00AC, 0x00AD, 0x00AE, 0x00AF, 0x00B0, 0x00B1, 0x00B2, 0x00B3, 0x00B4, 0x00B5, 0x00B6,
    0x00C0, 0x00C1, 0x00C2, 0x00C3, 0x00C4, 0x00C5, 0x00C6, 0x00C7, 0x00C8, 0x00C9,
    0x00CA, 0x00CB, 0x00CC, 0x00CD, 0x00CE, 0x00CF, 0x00D0, 0x00D1, 0x00D2, 0x00D3,
    0x00D4, 0x00D5, 0x00D6, 0x00D7, 0x00D8, 0x00D9, 0x00DA, 0x00DB, 0x00DC, 0x00DD,
    0x00DE, 0x00DF, 0x00E0, 0x00E1, 0x00E2, 0x00E3, 0x00E4, 0x00E5, 0x00E6, 0x00E7,
    0x0152, 0x0153, 0x0160, 0x0161, 0x0178, 0x0192, 0x02C6, 0x02DC,
    0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A, 0x2122, 0x2219
]

img = Image.new('RGB', (1200, 1000), 'white')
draw = ImageDraw.Draw(img)

cols = 6
for idx, code in enumerate(codes_to_check):
    if code not in cmap:
        continue
    char = chr(code)
    col = idx % cols
    row = idx // cols
    x = col * 200 + 20
    y = row * 80 + 20
    draw.text((x, y), f"0x{code:04X} ({code})", fill='blue', font=label_font)
    draw.text((x + 10, y + 22), char, fill='black', font=font)

img.save("scratch/ru_and_special_glyphs.png")
print("Saved to scratch/ru_and_special_glyphs.png")
